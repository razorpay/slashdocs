const webOAuthStateAudience = "oauth-state"

// cliExchangeResponse is the payload of POST /v1/auth/cli/exchange.
type cliExchangeResponse struct {
	ID        string               `json:"id"`
	Token     string               `json:"token"`
	Principal cliExchangePrincipal `json:"principal"`
}

type cliExchangePrincipal struct {
	Type  string `json:"type"`
	ID    string `json:"id"`
	Email string `json:"email"`
}

// discoveryResponse is the payload of GET /.well-known/slashdocs.json.
type discoveryResponse struct {
	Name       string        `json:"name"`
	APIVersion string        `json:"api_version"`
	Auth       discoveryAuth `json:"auth"`
}

type discoveryAuth struct {
	Modes []string `json:"modes"`
}

// configResponse is the payload of GET /v1/config.
type configResponse struct {
	Deployment           string `json:"deployment"`
	OrgName              string `json:"org_name"`
	EveryoneLabel        string `json:"everyone_label"`
	ProviderName         string `json:"provider_name"`
	DefaultDocPermission string `json:"default_doc_permission"`
	GoogleGroupsEnabled  bool   `json:"google_groups_enabled"`
	LabelsEnabled        bool   `json:"labels_enabled"`
}

// meResponse is the payload of GET /v1/me. Exactly one of User and
// ServiceAccount is set, matching the principal type.
type meResponse struct {
	Principal      principalRef      `json:"principal"`
	User           *userResponse     `json:"user,omitempty"`
	ServiceAccount *meServiceAccount `json:"service_account,omitempty"`
}

// principalRef identifies a principal by type and ID only.
type principalRef struct {
	Type auth.PrincipalType `json:"type"`
	ID   string             `json:"id"`
}

type meServiceAccount struct {
	ID       string         `json:"id"`
	Name     string         `json:"name"`
	Disabled bool           `json:"disabled"`
	Owner    meServiceOwner `json:"owner"`
}

type meServiceOwner struct {
	ID    string `json:"id"`
	Email string `json:"email"`
	Name  string `json:"name"`
}

// OAuthStart godoc
// @Summary Start OIDC login
// @Tags auth
// @Param mode query string false "web or cli"
// @Param redirect query string false "web redirect"
// @Param cli_redirect query string false "CLI loopback redirect"
// @Param code_challenge query string false "PKCE challenge"
// @Param state query string false "CLI correlation state; web state is generated by the server"
// @Success 302
// @Router /v1/auth/oidc/start [get]
// @Router /v1/auth/google/start [get]
func (h handlers) oauthStart(c *gin.Context) {
	mode := c.DefaultQuery("mode", authModeWeb)
	st := auth.LoginState{
		Mode:               mode,
		Redirect:           c.Query("redirect"),
		CLIRedirect:        c.Query("cli_redirect"),
		CodeChallenge:      c.Query("code_challenge"),
		ExpiresAt:          time.Now().Add(10 * time.Minute),
		WebBindingRequired: mode == authModeWeb,
	}
	if message := loginStateValidationError(st); message != "" {
		badRequest(c, message)
		return
	}
	state := c.Query("state")
	if mode == authModeWeb {
		// Web state is always server-generated. Accepting a caller-selected value
		// would let an attacker fix the victim's browser-binding cookie.
		state = ""
	}
	if state == "" {
		var err error
		state, err = auth.RandomURLToken()
		if err != nil {
			internalErr(c, err)
			return
		}
	}
	if err := h.deps.stateStore.PutState(c.Request.Context(), state, st); err != nil {
		internalErr(c, err)
		return
	}
	if mode == authModeWeb {
		h.setWebOAuthStateCookie(c, state, 10*time.Minute)
	}
	var opts []oauth2.AuthCodeOption
	if h.deps.oidc.Issuer == auth.GoogleIssuer {
		opts = append(opts, oauth2.AccessTypeOffline)
		if hd := googleHostedDomain(h.deps.deployment, h.deps.allowedOAuthDomains); hd != "" {
			opts = append(opts, oauth2.SetAuthURLParam("hd", hd))
		}
	}
	// nosemgrep: go.gin.ssrf.gin-tainted-url-host.gin-tainted-url-host - the issuer's discovered auth endpoint fixes the redirect host; state is encoded as an OAuth query parameter.
	c.Redirect(http.StatusFound, h.deps.oidc.AuthCodeURL(state, opts...))
}

func loginStateValidationError(st auth.LoginState) string {
	switch st.Mode {
	case authModeWeb:
		if !safeWebRedirect(st.Redirect) {
			return "invalid redirect"
		}
	case authModeCLI:
		if st.CodeChallenge == "" || !auth.LoopbackRedirectAllowed(st.CLIRedirect) {
			return "invalid cli oauth parameters"
		}
	default:
		return "invalid oauth mode"
	}
	return ""
}

// googleHostedDomain returns the Google `hd` login hint for org deployments
// with a single allowed domain, pre-filtering the account picker to that
// domain. It only shapes the login UX; the post-auth email-domain check in
// oauthCallback remains the enforcement.
func googleHostedDomain(deployment string, allowedDomains []string) string {
	if deployment == DeploymentOrg && len(allowedDomains) == 1 {
		return allowedDomains[0]
	}
	return ""
}

// OAuthCallback godoc
// @Summary OIDC login callback
// @Tags auth
// @Param code query string true "OAuth code"
// @Param state query string true "OAuth state"
// @Success 302
// @Router /v1/auth/oidc/callback [get]
// @Router /v1/auth/google/callback [get]
func (h handlers) oauthCallback(c *gin.Context) {
	state := c.Query("state")
	st, ok, err := h.deps.stateStore.TakeState(c.Request.Context(), state)
	if err != nil {
		internalErr(c, err)
		return
	}
	if !ok {
		badRequest(c, "invalid oauth state")
		return
	}
	if loginStateValidationError(st) != "" {
		badRequest(c, "invalid oauth state")
		return
	}
	if !h.validWebOAuthStateBinding(c, st, state) {
		badRequest(c, "invalid oauth state")
		return
	}
	metricKind := oidcAuthMetricKind(h.deps.oidc.Issuer)
	u, err := h.deps.oidc.ExchangeAndVerify(c.Request.Context(), c.Query("code"))
	if err != nil {
		slog.WarnContext(c.Request.Context(), "oidc login failed", slog.Any("error", err))
		incAuth(metricKind, "failure")
		c.JSON(http.StatusUnauthorized, errorResponse("unauthorized", "oidc login failed", nil))
		return
	}
	if !emailDomainAllowed(u.Email, h.deps.allowedOAuthDomains) {
		incAuth(metricKind, "forbidden_domain")
		c.JSON(http.StatusForbidden, errorResponse("forbidden", "account domain is not allowed", nil))
		return
	}
	uid, externalSubject := oidcIdentityKeys(h.deps.oidc.Issuer, u.Sub)
	p, err := h.deps.repository.UpsertGoogleUser(c.Request.Context(), uid, u.Email, u.Name, externalSubject, u.PictureURL)
	if err != nil {
		internalErr(c, err)
		return
	}
	if st.Mode == authModeCLI {
		code, err := auth.RandomURLToken()
		if err != nil {
			internalErr(c, err)
			return
		}
		st.User = u
		st.UserID = p.ID
		if err := h.deps.stateStore.PutCode(c.Request.Context(), code, st); err != nil {
			internalErr(c, err)
			return
		}
		u, _ := url.Parse(st.CLIRedirect)
		q := u.Query()
		q.Set("code", code)
		q.Set("state", c.Query("state"))
		u.RawQuery = q.Encode()
		c.Redirect(http.StatusFound, u.String())
		return
	}
	incAuth(metricKind, "success")
	h.setSessionCookie(c, p)
	redir := st.Redirect
	if redir == "" {
		redir = "/"
	}
	c.Redirect(http.StatusFound, redir)
}

func oidcAuthMetricKind(issuer string) string {
	if issuer == auth.GoogleIssuer {
		return "google"
	}
	return "oidc"
}

func (h handlers) validWebOAuthStateBinding(c *gin.Context, st auth.LoginState, state string) bool {
	if st.Mode != authModeWeb || !st.WebBindingRequired {
		return true
	}
	cookie, err := c.Request.Cookie(webOAuthStateCookieName(state, secureCookiesForOrigin(h.deps.appOrigin)))
	h.setWebOAuthStateCookie(c, state, -1)
	if err != nil {
		return false
	}
	boundState, ok := (auth.SessionCodec{Secret: []byte(h.deps.sessionSecret)}).VerifyAudience(cookie.Value, webOAuthStateAudience)
	return ok && boundState == state
}

// oidcIdentityKeys returns the application user ID and the external identity
// key persisted in users.google_sub. Google keeps its historical raw-sub
// representation for backwards compatibility. Generic OIDC identities hash
// the exact, verified issuer identifier with the subject so equal subjects
// from different issuers cannot collide. The versioned domain separator keeps
// the namespace deterministic and bounded without treating issuer host aliases
// as equivalent identifiers. The separator keeps the pre-rename "aidocs" name:
// changing it would give every existing OIDC user a new identity.
func oidcIdentityKeys(issuer, subject string) (userID, externalSubject string) {
	if issuer == auth.GoogleIssuer {
		return googleUserIDPrefix + subject, subject
	}
	digest := sha256.Sum256([]byte("aidocs-oidc-subject-v1\x00" + issuer + "\x00" + subject))
	namespace := hex.EncodeToString(digest[:])
	return oidcUserIDPrefix + namespace, "oidc_sha256_" + namespace
}

func webOAuthStateCookieName(state string, secure bool) string {
	digest := sha256.Sum256([]byte(state))
	prefix := "slashdocs_oauth_state_"
	if secure {
		// Browsers only accept __Host- cookies when they are Secure, host-only,
		// and scoped to Path=/, preventing sibling subdomains from cookie tossing.
		prefix = "__Host-" + prefix
	}
	return prefix + hex.EncodeToString(digest[:])
}

func (h handlers) setWebOAuthStateCookie(c *gin.Context, state string, lifetime time.Duration) {
	secure := secureCookiesForOrigin(h.deps.appOrigin)
	maxAge := int(lifetime / time.Second)
	expires := time.Now().Add(lifetime)
	value := ""
	if lifetime < 0 {
		maxAge = -1
		expires = time.Unix(1, 0)
	} else {
		value = (auth.SessionCodec{Secret: []byte(h.deps.sessionSecret)}).SignForAudience(state, webOAuthStateAudience, lifetime)
	}
	//nolint:gosec // G124: Secure is deliberately false only for configured local HTTP development origins.
	http.SetCookie(c.Writer, &http.Cookie{
		Name:     webOAuthStateCookieName(state, secure),
		Value:    value,
		Path:     "/",
		MaxAge:   maxAge,
		Expires:  expires,
		Secure:   secure,
		HttpOnly: true,
		SameSite: http.SameSiteLaxMode,
	})
}

// secureCookiesForOrigin derives cookie policy from the validated public app
// origin. Plain HTTP remains supported for local development only.
func secureCookiesForOrigin(origin string) bool {
	u, err := url.Parse(origin)
	return err == nil && u.Host != "" && strings.EqualFold(u.Scheme, "https")
}

// CLIExchange godoc
// @Summary Exchange CLI login code
// @Tags auth
// @Accept json
// @Produce json
// @Success 200 {object} cliExchangeResponse
// @Failure 401 {object} errorEnvelope
// @Router /v1/auth/cli/exchange [post]
func (h handlers) cliExchange(c *gin.Context) {
	var in struct {
		Code         string `json:"code"`
		CodeVerifier string `json:"code_verifier"`
		Name         string `json:"name"`
	}
	if !requireJSON(c) {
		return
	}
	if err := c.ShouldBindJSON(&in); err != nil || in.Code == "" || in.CodeVerifier == "" {
		badRequest(c, "invalid cli exchange")
		return
	}
	st, ok, err := h.deps.stateStore.TakeCode(c.Request.Context(), in.Code)
	if err != nil {
		internalErr(c, err)
		return
	}
	if !ok || st.Mode != authModeCLI || !auth.VerifyPKCES256(in.CodeVerifier, st.CodeChallenge) {
		incAuth("cli_exchange", "failure")
		c.JSON(http.StatusUnauthorized, errorResponse("unauthorized", "invalid cli code", nil))
		return
	}
	token, hash, err := auth.NewBearerToken("slashdocs_cli_")
	if err != nil {
		internalErr(c, err)
		return
	}
	name := in.Name
	if name == "" {
		name = "cli"
	}
	id, err := h.deps.repository.CreateCLICredential(c.Request.Context(), st.UserID, name, hash)
	if err != nil {
		internalErr(c, err)
		return
	}
	incAuth("cli_exchange", "success")
	c.JSON(http.StatusOK, cliExchangeResponse{ID: id, Token: token, Principal: cliExchangePrincipal{Type: "user", ID: st.UserID, Email: st.User.Email}})
}

// ListCLICredentials godoc
// @Summary List CLI credentials
// @Tags auth
// @Security bearerAuth
// @Security cookieAuth
// @Produce json
// @Success 200 {object} listResponse[repo.CLICredential]
// @Router /v1/auth/cli/credentials [get]
func (h handlers) listCLICredentials(c *gin.Context) {
	p := current(c)
	items, err := h.deps.repository.ListCLICredentials(c.Request.Context(), p.ID)
	if err != nil {
		internalErr(c, err)
		return
	}
	c.JSON(http.StatusOK, listResponse[repo.CLICredential]{Items: items})
}

// RevokeCLICredential godoc
// @Summary Revoke CLI credential
// @Tags auth
// @Security bearerAuth
// @Security cookieAuth
// @Param id path string true "Credential ID"
// @Success 204
// @Router /v1/auth/cli/credentials/{id} [delete]
func (h handlers) revokeCLICredential(c *gin.Context) {
	p := current(c)
	if err := h.deps.repository.RevokeCLICredential(c.Request.Context(), p.ID, c.Param("id")); err != nil {
		internalErr(c, err)
		return
	}
	c.Status(http.StatusNoContent)
}

// Logout godoc
// @Summary End the browser session
// @Description Clears the session cookie. CLI credentials stay valid.
// @Tags auth
// @Success 204
// @Router /v1/auth/logout [post]
func (h handlers) logout(c *gin.Context) {
	h.writeSessionCookie(c, "", -1)
	c.Status(http.StatusNoContent)
}

func (h handlers) setSessionCookie(c *gin.Context, p auth.Principal) {
	h.writeSessionCookie(c, (auth.SessionCodec{Secret: []byte(h.deps.sessionSecret)}).Sign(p.ID), sessionTTLSeconds)
}

// writeSessionCookie sets the session cookie. A negative maxAge deletes it.
func (h handlers) writeSessionCookie(c *gin.Context, value string, maxAge int) {
	//nolint:gosec // G124: Secure is deliberately false only for configured local HTTP development origins.
	http.SetCookie(c.Writer, &http.Cookie{
		Name:     sessionCookieName,
		Value:    value,
		MaxAge:   maxAge,
		Path:     "/",
		Secure:   secureCookiesForOrigin(h.deps.appOrigin),
		HttpOnly: true,
		SameSite: http.SameSiteLaxMode,
	})
}

// Discovery godoc
// @Summary Deployment discovery
// @Tags discovery
// @Produce json
// @Success 200 {object} discoveryResponse
// @Router /.well-known/slashdocs.json [get]
func (h handlers) discovery(c *gin.Context) {
	c.JSON(http.StatusOK, discoveryResponse{Name: "slashdocs", APIVersion: "v1", Auth: discoveryAuth{Modes: []string{authModeWeb, authModeCLI, "mcp"}}})
}

// everyoneLabel is the human label for the "anyone" grant on this deployment.
// Public servers grant anyone with the link; org servers grant the org's
// members (scoped by the login gate, not the network).
func everyoneLabel(deployment, orgName string) string {
	if deployment == DeploymentOrg {
		if orgName != "" {
			return "Anyone in " + orgName
		}
		return "Anyone in the org"
	}
	return "Anyone with the link"
}

// defaultProviderName labels the login button; "SSO" is the neutral fallback
// for deployments that predate SLASHDOCS_OIDC_PROVIDER_NAME.
func defaultProviderName(name string) string {
	if name == "" {
		return "SSO"
	}
	return name
}

// Config godoc
// @Summary Deployment configuration
// @Tags discovery
// @Produce json
// @Success 200 {object} configResponse
// @Router /v1/config [get]
func (h handlers) config(c *gin.Context) {
	deployment := h.deps.deployment
	if deployment == "" {
		deployment = DeploymentPublic
	}
	c.JSON(http.StatusOK, configResponse{
		Deployment:           deployment,
		OrgName:              h.deps.orgName,
		EveryoneLabel:        everyoneLabel(deployment, h.deps.orgName),
		ProviderName:         defaultProviderName(h.deps.oidcProviderName),
		DefaultDocPermission: defaultDocPermissionLabel(h.deps.defaultDocPermission),
		GoogleGroupsEnabled:  h.deps.googleGroupsEnabled,
		LabelsEnabled:        h.deps.labelsEnabled,
	})
}

// defaultDocPermissionLabel spells the server-wide default in the wire
// vocabulary, where repo.RoleNone reads as "private".
func defaultDocPermissionLabel(role repo.Role) string {
	if role == repo.RoleNone {
		return "private"
	}
	return string(role)
}

// CommitTXT godoc
// @Summary Build commit SHA
// @Tags discovery
// @Produce plain
// @Success 200 {string} string
// @Router /commit.txt [get]
func (h handlers) commitTXT(c *gin.Context) {
	sha := releaseCommit()
	if sha == "" {
		sha = os.Getenv("SLASHDOCS_COMMIT_SHA")
	}
	if sha == "" {
		sha = os.Getenv("COMMIT_SHA")
	}
	c.String(http.StatusOK, sha)
}

// Me godoc
// @Summary Current principal
// @Tags auth
// @Produce json
// @Security bearerAuth
// @Security cookieAuth
// @Success 200 {object} meResponse
// @Failure 401 {object} errorEnvelope
// @Router /v1/me [get]
func (h handlers) me(c *gin.Context) {
	p := current(c)
	out := meResponse{Principal: principalRef{Type: p.Type, ID: p.ID}}
	if p.Type == auth.PrincipalUser {
		user := userJSON(*p)
		out.User = &user
	} else {
		sa, err := h.deps.repository.GetServiceAccount(c.Request.Context(), p.ID)
		if err != nil {
			internalErr(c, err)
			return
		}
		out.ServiceAccount = &meServiceAccount{
			ID:       sa.ID,
			Name:     sa.Name,
			Disabled: sa.Disabled,
			Owner:    meServiceOwner{ID: sa.Owner.ID, Email: sa.Owner.Email, Name: sa.Owner.Name},
		}
	}
	c.JSON(http.StatusOK, out)
}
