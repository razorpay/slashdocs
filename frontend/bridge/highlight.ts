// Highlight painting for resolved anchor ranges.
//
// The text-node collection and wrapping strategy is ported from the
// Hypothesis client (src/annotator/highlighter.ts and
// src/annotator/range-util.ts, BSD-2-Clause): boundary text nodes are split,
// whole text nodes inside the range are grouped into spans of adjacent
// siblings, and each span is wrapped in a highlight element. Unlike the old
// `Range.surroundContents` approach this never throws on ranges that cross
// element boundaries.
//
// Spans inside SVG content cannot be wrapped (non-SVG children of `<text>`
// don't render), so those get a `<rect>` overlay behind the text instead.

const SVG_NS = "http://www.w3.org/2000/svg";

/**
 * Returns true if any part of `node` lies within `range`.
 */
function isNodeInRange(range: Range, node: Node): boolean {
  try {
    const length = node.nodeValue?.length ?? node.childNodes.length;
    return (
      // Check start of node is before end of range.
      range.comparePoint(node, 0) <= 0 &&
      // Check end of node is after start of range.
      range.comparePoint(node, length) >= 0
    );
  } catch {
    // `comparePoint` may fail if the `range` and `node` do not share a common
    // ancestor or `node` is a doctype.
    return false;
  }
}

/**
 * Return text nodes which are entirely inside `range`.
 *
 * If a range starts or ends part-way through a text node, the node is split
 * and the part inside the range is returned.
 */
function wholeTextNodesInRange(range: Range): Text[] {
  if (range.collapsed) {
    // Exit early for an empty range to avoid an edge case that breaks the
    // algorithm below. Splitting a text node at the start of an empty range
    // can leave the range ending in the left part rather than the right part.
    return [];
  }

  let root = range.commonAncestorContainer as Node | null;
  if (root && root.nodeType !== Node.ELEMENT_NODE) {
    // If the common ancestor is not an element, set it to the parent element
    // to ensure that the loop below visits any text nodes generated by
    // splitting the common ancestor.
    root = root.parentElement;
  }
  if (!root) {
    return [];
  }

  const textNodes: Text[] = [];
  const nodeIter = root.ownerDocument!.createNodeIterator(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = nodeIter.nextNode())) {
    if (!isNodeInRange(range, node)) {
      continue;
    }
    const text = node as Text;

    if (text === range.startContainer && range.startOffset > 0) {
      // Split `text` where the range starts. The split will create a new
      // `Text` node which will be in the range and will be visited in the
      // next loop iteration.
      text.splitText(range.startOffset);
      continue;
    }

    if (text === range.endContainer && range.endOffset < text.data.length) {
      // Split `text` where the range ends, leaving it as the part in the range.
      text.splitText(range.endOffset);
    }

    textNodes.push(text);
  }

  return textNodes;
}

/**
 * Draw a highlight `<rect>` behind the SVG element containing `n`, since SVG
 * text cannot be wrapped in an HTML `<mark>`. Returns the number of visual
 * artifacts created (0 when the element has no renderable box).
 */
function svgHighlight(
  n: Text,
  active: boolean,
  id: string | undefined,
  scroll: boolean,
): number {
  const el = n.parentElement as SVGGraphicsElement | null;
  if (!el || !el.getBBox) {
    return 0;
  }
  // Reuse the existing rect when several text nodes of one comment live in
  // the same SVG element (e.g. a <text> with <tspan> children).
  if (id && el.dataset.cid === id && el.classList.contains("slashdocs-svg-mark-text")) {
    return 1;
  }
  let box;
  try {
    box = el.getBBox();
  } catch {
    return 0;
  }
  if (!box || box.width <= 0 || box.height <= 0) {
    return 0;
  }
  const rect = el.ownerDocument.createElementNS(SVG_NS, "rect");
  rect.classList.add("slashdocs-svg-mark-rect");
  if (active) {
    rect.classList.add("slashdocs-mark-active");
  }
  if (id) {
    rect.dataset.cid = id;
    el.dataset.cid = id;
  }
  rect.setAttribute("x", String(box.x - 3));
  rect.setAttribute("y", String(box.y - 2));
  rect.setAttribute("width", String(box.width + 6));
  rect.setAttribute("height", String(box.height + 4));
  el.parentNode!.insertBefore(rect, el);
  el.classList.add("slashdocs-svg-mark-text");
  if (active && scroll) {
    el.scrollIntoView({ block: "center", behavior: "smooth" });
  }
  return 1;
}

/**
 * Highlight the text content of `range`, tagging every created artifact with
 * the comment id. Returns the number of visual artifacts created; `0` means
 * the range contained nothing highlightable and the caller should treat the
 * comment as unanchored. `scroll` gates the scroll-into-view of the active
 * comment: paints triggered by document mutations must not move the user's
 * scroll position.
 */
export function highlightRange(
  range: Range,
  active: boolean,
  id: string | undefined,
  scroll: boolean,
): number {
  const textNodes = wholeTextNodesInRange(range);

  // Group text nodes into spans of adjacent siblings so one highlight element
  // wraps each run.
  const textNodeSpans: Text[][] = [];
  let prevNode: Node | null = null;
  for (const node of textNodes) {
    if (prevNode && prevNode.nextSibling === node) {
      textNodeSpans[textNodeSpans.length - 1].push(node);
    } else {
      textNodeSpans.push([node]);
    }
    prevNode = node;
  }

  const whitespace = /^\s*$/;
  let count = 0;
  let scrollTarget: Element | null = null;

  for (const nodes of textNodeSpans) {
    const parent = nodes[0].parentElement;
    if (!parent) {
      continue;
    }

    // Skip whitespace-only spans: they add no visible highlight, and
    // inserting elements is invalid in containers with restricted content
    // models such as <table> rows and lists. (A lone whitespace <span> child
    // is kept, mirroring Hypothesis, since it can affect layout in code
    // editors.)
    const whitespaceOnly = nodes.every((node) => whitespace.test(node.data));
    const loneSpanChild = parent.childNodes.length === 1 && parent.tagName === "SPAN";
    if (whitespaceOnly && !loneSpanChild) {
      continue;
    }

    if (parent.namespaceURI === SVG_NS) {
      for (const node of nodes) {
        count += svgHighlight(node, active, id, scroll);
      }
      continue;
    }

    const mark = parent.ownerDocument.createElement("mark");
    mark.className = "slashdocs-mark" + (active ? " slashdocs-mark-active" : "");
    if (id) {
      mark.dataset.cid = id;
    }
    parent.replaceChild(mark, nodes[0]);
    for (const node of nodes) {
      mark.appendChild(node);
    }
    if (!scrollTarget) {
      scrollTarget = mark;
    }
    count += 1;
  }

  if (active && scroll && scrollTarget) {
    scrollTarget.scrollIntoView({ block: "center", behavior: "smooth" });
  }
  return count;
}

/**
 * Remove every highlight artifact previously created by `highlightRange` and
 * merge the text nodes that wrapping split apart.
 */
export function clearHighlights(d: Document): void {
  const parents = new Set<Node>();
  d.querySelectorAll("mark.slashdocs-mark").forEach((m) => {
    if (m.parentNode) {
      parents.add(m.parentNode);
    }
    m.replaceWith(...m.childNodes);
  });
  d.querySelectorAll(".slashdocs-svg-mark-rect").forEach((r) => r.remove());
  d.querySelectorAll<HTMLElement>(".slashdocs-svg-mark-text").forEach((t) => {
    t.classList.remove("slashdocs-svg-mark-text");
    delete t.dataset.cid;
  });
  // Merge only the text nodes our wrapping split apart. A whole-body
  // normalize() would also merge or drop text nodes created by the
  // document's own scripts, breaking any references those scripts hold.
  parents.forEach((p) => p.normalize());
}

/**
 * Remove only the artifacts of one comment, leaving every other highlight
 * untouched. Used by mutation-driven repair so an unrelated DOM change never
 * rebuilds the whole overlay. Returns the number of artifacts removed.
 */
export function clearHighlightsFor(d: Document, id: string): number {
  const cid = CSS.escape(id);
  const parents = new Set<Node>();
  let removed = 0;
  d.querySelectorAll('mark.slashdocs-mark[data-cid="' + cid + '"]').forEach((m) => {
    if (m.parentNode) {
      parents.add(m.parentNode);
    }
    m.replaceWith(...m.childNodes);
    removed += 1;
  });
  d.querySelectorAll('.slashdocs-svg-mark-rect[data-cid="' + cid + '"]').forEach(
    (r) => {
      r.remove();
      removed += 1;
    },
  );
  d.querySelectorAll<HTMLElement>(
    '.slashdocs-svg-mark-text[data-cid="' + cid + '"]',
  ).forEach((t) => {
    t.classList.remove("slashdocs-svg-mark-text");
    delete t.dataset.cid;
  });
  parents.forEach((p) => p.normalize());
  return removed;
}

/**
 * Recompute the geometry of SVG highlight rects. They are the one artifact
 * that goes stale when a document mutation shifts layout without touching
 * the highlighted text itself.
 */
export function refreshSVGRects(d: Document): void {
  d.querySelectorAll(".slashdocs-svg-mark-rect").forEach((rect) => {
    // svgHighlight inserts the rect immediately before the element it
    // covers; several comments on one element stack contiguous rects.
    let target = rect.nextElementSibling;
    while (target && target.classList.contains("slashdocs-svg-mark-rect")) {
      target = target.nextElementSibling;
    }
    const el = target as SVGGraphicsElement | null;
    if (!el || !el.classList.contains("slashdocs-svg-mark-text") || !el.getBBox) {
      rect.remove();
      return;
    }
    let box;
    try {
      box = el.getBBox();
    } catch {
      rect.remove();
      return;
    }
    rect.setAttribute("x", String(box.x - 3));
    rect.setAttribute("y", String(box.y - 2));
    rect.setAttribute("width", String(box.width + 6));
    rect.setAttribute("height", String(box.height + 4));
  });
}
