import { useMutation, useQueryClient } from "@tanstack/react-query";
import { Pencil } from "lucide-react";
import { toast } from "sonner";
import { api, APIError } from "@/api";
import { Button } from "@/components/ui/button";
import { errorMessage } from "@/lib/errors";
import { queryKeys } from "@/lib/queryKeys";
import { buildEdits } from "@/lib/text-edits";
import { useDoc } from "./doc-context";

// Raised to stop a save while keeping the reader's edits on screen.
class KeepEditing extends Error {}

// TextEditControls lets an editor change the words of the version on screen.
// Saving sends only exact find-and-replace edits, the same ones an agent
// sends, and the server applies them to the current version: someone else's
// edits to other text since the reader started are kept, not overwritten.
export function TextEditControls({
  docId,
  version,
  onSaved,
}: {
  docId: string;
  version: string;
  onSaved: (versionID: string) => void;
}) {
  const q = useQueryClient();
  const { textEditing, setTextEditing, textEditCount, collectTextEdits } = useDoc();

  const save = useMutation({
    mutationFn: async () => {
      const { changes, unsupported } = await collectTextEdits();
      if (unsupported) {
        throw new KeepEditing(
          "Some changes add or remove structure, such as paragraphs. Only words can be saved here: cancel, or upload a new version.",
        );
      }
      if (!changes.length) return null;
      const source = await api.getVersionHTML(docId, version);
      const { edits, unmatched } = buildEdits(source, changes);
      if (unmatched.length) {
        const first = unmatched[0].before.trim().slice(0, 60);
        throw new KeepEditing(
          unmatched[0].reason === "ambiguous"
            ? `“${first}” appears more than once in the document, so the change can't be placed. Change a longer passage around it.`
            : `“${first}” is not in the document source as written (it may be generated by a script). Undo that change to save the rest.`,
        );
      }
      if (!edits.length) return null;
      return api.editDocument(docId, { edits });
    },
    onSuccess: (saved) => {
      setTextEditing(false);
      if (!saved) {
        toast.info("No changes to save.");
        return;
      }
      toast.success(`Saved version ${saved.number}.`);
      q.invalidateQueries({ queryKey: queryKeys.versions(docId) });
      q.invalidateQueries({ queryKey: queryKeys.document(docId) });
      q.invalidateQueries({ queryKey: queryKeys.comments(docId) });
      onSaved(saved.id);
    },
    onError: (e) => {
      if (e instanceof APIError && e.code === "edit_failed") {
        toast.error(
          "Someone changed this text since you started editing, so nothing was saved. Copy your changes, cancel, and edit the latest version.",
        );
        return;
      }
      toast.error(errorMessage(e, "Could not save the edits."));
    },
  });

  if (!textEditing) {
    return (
      <Button
        variant="ghost"
        size="icon"
        className="shrink-0"
        title="Edit text"
        aria-label="Edit text"
        onClick={() => setTextEditing(true)}
      >
        <Pencil className="h-4 w-4" />
      </Button>
    );
  }
  return (
    <div
      role="group"
      aria-label="Editing text"
      className="flex shrink-0 items-center gap-1.5 rounded-full bg-[var(--color-surface-muted)] py-0.5 pl-3 pr-0.5"
    >
      <span className="hidden text-xs tabular-nums text-[var(--color-fg-muted)] sm:inline">
        {textEditCount === 0
          ? "Editing"
          : `${textEditCount} ${textEditCount === 1 ? "change" : "changes"}`}
      </span>
      <Button
        variant="ghost"
        size="sm"
        disabled={save.isPending}
        onClick={() => setTextEditing(false)}
      >
        Cancel
      </Button>
      <Button size="sm" disabled={save.isPending} onClick={() => save.mutate()}>
        {save.isPending ? "Saving…" : "Save"}
      </Button>
    </div>
  );
}
