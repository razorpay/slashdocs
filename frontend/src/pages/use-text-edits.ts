import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { useQueryClient } from "@tanstack/react-query";
import { toast } from "sonner";
import { api, APIError } from "@/api";
import { errorMessage } from "@/lib/errors";
import { queryKeys } from "@/lib/queryKeys";
import type { CommentAnchor } from "../../bridge/anchoring";
import {
  applyEdits,
  locateForEdit,
  reapplyEdits,
  summaryLines,
  type TextEdit,
} from "@/lib/text-edits/apply";
import type { LocatedRange } from "@/lib/text-edits/locate";
import { inlineText, sanitizeInline } from "@/lib/text-edits/sanitize";

// Where the selection sits in the frame's viewport, in unscaled frame pixels.
export type EditRect = { top: number; bottom: number; left: number };

export type TextEditDraft = {
  located: LocatedRange;
  seed: string;
  dropped: boolean;
  rect: EditRect;
};

export type TextEditsController = {
  // Whether the reader may start an edit on the version shown.
  enabled: boolean;
  // The version the edits apply to, once the first edit loaded it.
  baseVersion?: string;
  edits: TextEdit[];
  draft: TextEditDraft | null;
  // Changes whenever the frame must reload to drop previews.
  frameReload: number;
  saving: boolean;
  // The newer version a save ran into.
  conflict?: string;
  request: (anchor: CommentAnchor, rect: EditRect) => void;
  apply: (html: string) => void;
  cancel: () => void;
  remove: (id: string) => void;
  discard: () => void;
  defaultSummary: () => string;
  save: (summary: string) => Promise<boolean>;
  reapply: () => Promise<void>;
};

const REFUSALS: Record<string, string> = {
  generated: "This text is generated by the document and can't be edited here.",
  "crosses-blocks":
    "Select text within one paragraph, heading, list item, or table cell.",
  overlaps:
    "This text has an unsaved edit. Remove that edit from the list to change it again.",
  unsupported: "This text can't be edited here.",
};

export function useTextEdits({
  docId,
  canEdit,
  current,
  latest,
  onVersion,
}: {
  docId: string;
  canEdit: boolean;
  current?: string;
  latest?: string;
  // Shows a version: the one saved, or the one the edits moved to.
  onVersion: (version: string) => void;
}): TextEditsController {
  const q = useQueryClient();
  const [base, setBase] = useState<{ version: string; html: string }>();
  const [edits, setEdits] = useState<TextEdit[]>([]);
  const [draft, setDraft] = useState<TextEditDraft | null>(null);
  const [frameReload, setFrameReload] = useState(0);
  const [saving, setSaving] = useState(false);
  const [conflict, setConflict] = useState<string>();
  const loading = useRef<Promise<{ version: string; html: string }> | null>(null);

  const editVersion = edits.length && base ? base.version : latest;
  const enabled = canEdit && !conflict && !!current && current === editVersion;

  useEffect(() => {
    setBase(undefined);
    setEdits([]);
    setDraft(null);
    setConflict(undefined);
    loading.current = null;
  }, [docId]);

  useEffect(() => {
    if (!edits.length) return;
    const onBeforeUnload = (event: BeforeUnloadEvent) => {
      event.preventDefault();
      event.returnValue = "";
    };
    window.addEventListener("beforeunload", onBeforeUnload);
    return () => window.removeEventListener("beforeunload", onBeforeUnload);
  }, [edits.length]);

  const reloadFrame = useCallback(async () => {
    if (current) {
      await q.refetchQueries({ queryKey: queryKeys.render(docId, current) });
    }
    setFrameReload((n) => n + 1);
  }, [q, docId, current]);

  const loadBase = useCallback(
    (version: string) => {
      if (base?.version === version) return Promise.resolve(base);
      loading.current ??= api.versionHTML(docId, version).then(
        (html) => {
          const loaded = { version, html };
          setBase(loaded);
          loading.current = null;
          return loaded;
        },
        (err) => {
          loading.current = null;
          throw err;
        },
      );
      return loading.current;
    },
    [base, docId],
  );

  const request = useCallback(
    (anchor: CommentAnchor, rect: EditRect) => {
      if (!enabled || !editVersion) {
        toast.info("Switch to the latest version to edit.");
        return;
      }
      void loadBase(editVersion).then(
        (loaded) => {
          const located = locateForEdit(loaded.html, edits, anchor);
          if (typeof located === "string") {
            toast.info(REFUSALS[located]);
            return;
          }
          const { html, dropped } = sanitizeInline(located.html);
          setDraft({ located, seed: html, dropped, rect });
        },
        (err) => toast.error(errorMessage(err, "Could not load the document.")),
      );
    },
    [enabled, editVersion, loadBase, edits],
  );

  const apply = useCallback(
    (html: string) => {
      if (!draft) return;
      const clean = sanitizeInline(html).html;
      setDraft(null);
      if (clean === draft.seed) return;
      setEdits((list) => [
        ...list,
        {
          id: crypto.randomUUID(),
          start: draft.located.start,
          end: draft.located.end,
          originalHtml: draft.located.html,
          originalText: draft.located.text,
          html: clean,
          text: inlineText(clean),
          anchor: draft.located.anchor,
        },
      ]);
    },
    [draft],
  );

  const cancel = useCallback(() => setDraft(null), []);

  const remove = useCallback(
    (id: string) => {
      setEdits((list) => list.filter((edit) => edit.id !== id));
      void reloadFrame();
    },
    [reloadFrame],
  );

  const discard = useCallback(() => {
    setEdits([]);
    setDraft(null);
    setConflict(undefined);
    void reloadFrame();
  }, [reloadFrame]);

  const defaultSummary = useCallback(() => summaryLines(edits).join("\n"), [edits]);

  const save = useCallback(
    async (summary: string) => {
      if (!base || !edits.some((edit) => !edit.failed)) return false;
      setSaving(true);
      try {
        const html = applyEdits(base.html, edits);
        const file = new File([html], "document.html", { type: "text/html" });
        const version = await api.createVersion(docId, base.version, summary, file);
        setEdits([]);
        setBase(undefined);
        setConflict(undefined);
        toast.success("Edits saved as a new version.");
        // Move to the saved version first so it doesn't read as someone else's.
        onVersion(version.id);
        await Promise.all([
          q.invalidateQueries({ queryKey: queryKeys.versions(docId) }),
          q.invalidateQueries({ queryKey: queryKeys.document(docId) }),
          q.invalidateQueries({ queryKey: queryKeys.comments(docId) }),
        ]);
        return true;
      } catch (err) {
        if (err instanceof APIError && err.code === "version_conflict") {
          const details = err.details as { current_version_id?: string } | undefined;
          setConflict(details?.current_version_id || latest || base.version);
          return false;
        }
        toast.error(errorMessage(err, "Could not save the edits."));
        return false;
      } finally {
        setSaving(false);
      }
    },
    [base, edits, docId, q, onVersion, latest],
  );

  const reapply = useCallback(async () => {
    if (!conflict) return;
    try {
      const html = await api.versionHTML(docId, conflict);
      const moved = reapplyEdits(html, edits);
      const lost = moved.filter((edit) => edit.failed).length;
      setBase({ version: conflict, html });
      setEdits(moved);
      setConflict(undefined);
      onVersion(conflict);
      await q.invalidateQueries({ queryKey: queryKeys.versions(docId) });
      if (lost) {
        toast.warning(
          `${lost} ${lost === 1 ? "edit" : "edits"} could not be placed on the newer version.`,
        );
      }
    } catch (err) {
      toast.error(errorMessage(err, "Could not load the newer version."));
    }
  }, [conflict, docId, edits, q, onVersion]);

  return useMemo(
    () => ({
      enabled,
      baseVersion: base?.version,
      edits,
      draft,
      frameReload,
      saving,
      conflict,
      request,
      apply,
      cancel,
      remove,
      discard,
      defaultSummary,
      save,
      reapply,
    }),
    [
      enabled,
      base?.version,
      edits,
      draft,
      frameReload,
      saving,
      conflict,
      request,
      apply,
      cancel,
      remove,
      discard,
      defaultSummary,
      save,
      reapply,
    ],
  );
}
